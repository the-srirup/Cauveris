"""
Enums and states for the Cauveris Model Gateway.
"""

from enum import Enum


class ProviderState(str, Enum):
    """
    Explicit provider lifecycle and readiness states.
    Production states must never use mock or fixture identifiers.
    """
    NEBIUS_NVIDIA_ACTIVE = "NEBIUS_NVIDIA_ACTIVE"
    NEBIUS_NVIDIA_DEGRADED = "NEBIUS_NVIDIA_DEGRADED"
    LOCAL_DETERMINISTIC_ONLY = "LOCAL_DETERMINISTIC_ONLY"
    PROVIDER_UNAVAILABLE = "PROVIDER_UNAVAILABLE"
    CONFIGURATION_INVALID = "CONFIGURATION_INVALID"
    RATE_LIMITED = "RATE_LIMITED"
    CIRCUIT_OPEN = "CIRCUIT_OPEN"
    SAMPLE_DATA = "SAMPLE_DATA"


class ModelTaskType(str, Enum):
    """Explicit bounded tasks permitted for NVIDIA model assistance."""
    TERMINOLOGY_MAPPING = "TERMINOLOGY_MAPPING"
    LOG_CLUSTERING = "LOG_CLUSTERING"
    HYPOTHESIS_PROPOSAL = "HYPOTHESIS_PROPOSAL"
    REPAIR_STRATEGY_PROPOSAL = "REPAIR_STRATEGY_PROPOSAL"
    MISSING_EVIDENCE_RECOMMENDATION = "MISSING_EVIDENCE_RECOMMENDATION"
    EXPLANATION_GENERATION = "EXPLANATION_GENERATION"


class ModelAssistanceStatus(str, Enum):
    """Pipeline-stage states for model assistance visibility."""
    MODEL_ASSISTANCE_NOT_REQUIRED = "MODEL_ASSISTANCE_NOT_REQUIRED"
    MODEL_ASSISTANCE_QUEUED = "MODEL_ASSISTANCE_QUEUED"
    MODEL_ASSISTANCE_RUNNING = "MODEL_ASSISTANCE_RUNNING"
    MODEL_ASSISTANCE_VALIDATING = "MODEL_ASSISTANCE_VALIDATING"
    MODEL_ASSISTANCE_ACCEPTED = "MODEL_ASSISTANCE_ACCEPTED"
    MODEL_ASSISTANCE_PARTIAL = "MODEL_ASSISTANCE_PARTIAL"
    MODEL_ASSISTANCE_REJECTED = "MODEL_ASSISTANCE_REJECTED"
    MODEL_ASSISTANCE_FAILED = "MODEL_ASSISTANCE_FAILED"
    MODEL_ASSISTANCE_UNAVAILABLE = "MODEL_ASSISTANCE_UNAVAILABLE"


class ValidationResult(str, Enum):
    """Deterministic validation result of model proposals."""
    ACCEPTED = "ACCEPTED"
    PARTIAL = "PARTIAL"
    REJECTED = "REJECTED"
    ERROR = "ERROR"
